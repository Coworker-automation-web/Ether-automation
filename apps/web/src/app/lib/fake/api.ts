export interface MockApiOptions {
  readonly now?: () => number;
  /** Latency for plain requests (ms). */
  readonly delayMs?: number;
  /** Delay before the first token and between chunks (ms). */
  readonly streamDelayMs?: number;
  readonly generationLimit?: number;
  readonly summaryLimit?: number;
}

const abortError = (): DOMException => new DOMException("Aborted", "AbortError");

function sleep(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) return reject(abortError());
    if (ms <= 0) return resolve();
    const onAbort = (): void => {
      clearTimeout(timer);
      reject(abortError());
    };
    const timer = setTimeout(() => {
      signal?.removeEventListener("abort", onAbort);
      resolve();
    }, ms);
    signal?.addEventListener("abort", onAbort, { once: true });
  });
}

const AGENT_LABEL: Record<AiAgent, string> = {
  default: "Default Agent",
  fast: "Fast Agent",
  creative: "Creative Agent",
  research: "Research Agent",
};

/** Canned markdown per tool. Triggers for dev: "[limit]", "[daily]", "[fail]", "[midfail]" in the prompt. */
export function cannedMarkdown(tool: AiTool, agent: AiAgent): string {
  const by = `Generated by **${AGENT_LABEL[agent]}**.`;
  switch (tool) {
    case "plan":
      return [
        "## Execution Plan",
        by,
        "### Steps",
        "1. Define the objective and the measure of success",
        "2. Break the work into milestones with owners",
        "3. Schedule a review after the first milestone",
        "",
        "> Revisit the plan weekly and adjust scope early.",
      ].join("\n\n");
    case "blueprint":
      return [
        "## System Blueprint",
        by,
        "### Components",
        "- **Client:** Astro shell with a lazily loaded editor",
        "- **Edge:** Worker routes, one live room per workspace",
        "- **Storage:** Relational metadata with private object storage",
        "",
        "Review each boundary for access checks before building.",
      ].join("\n\n");
    default:
      return [
        "## New Document Draft",
        by,
        "### Overview",
        "Here is your generated structured outline. You can freely *edit*, format, or extend any part of this canvas directly.",
        "- **Core Concept:** Accelerated ideation with ambient AI assistance",
        "- **Next Steps:** Refine document sections or export to library",
      ].join("\n\n");
  }
}

export function chunkText(value: string, size = 24): string[] {
  const out: string[] = [];
  for (let i = 0; i < value.length; i += size) out.push(value.slice(i, i + size));
  return out;
}

function plainText(node: DocNode): string {
  if (node.text !== undefined) return node.text;
  return (node.content ?? []).map(plainText).join(" ");
}

export function createMockApi(options: MockApiOptions = {}): EtherApi {
  const now = options.now ?? ((): number => Math.floor(Date.now() / 1000));
  const delayMs = options.delayMs ?? 250;
  const streamDelayMs = options.streamDelayMs ?? 60;
  const generationLimit = options.generationLimit ?? 15;
  const summaryLimit = options.summaryLimit ?? 60;

  const workspaces = new Map<string, MockSnapshot[]>();
  const keys = new Map<string, string>();
  let generations = 0;
  let summaries = 0;
  let nextId = 1;

  const snapshotsFor = (workspaceId: string): MockSnapshot[] => {
    let list = workspaces.get(workspaceId);
    if (!list) {
      list = seedSnapshots(now());
      workspaces.set(workspaceId, list);
    }
    return list;
  };
  const strip = ({ content: _content, ...snapshot }: MockSnapshot): Snapshot => snapshot;
  const resetAt = (): number => (Math.floor(now() / 86400) + 1) * 86400;

  return {
    async getMe(signal) {
      await sleep(delayMs, signal);
      return MOCK_ME;
    },

    async listSnapshots(workspaceId, signal) {
      await sleep(delayMs, signal);
      return [...snapshotsFor(workspaceId)].sort((a, b) => b.created_at - a.created_at).map(strip);
    },

    async createSnapshot(workspaceId, title) {
      await sleep(delayMs);
      const current = getMockRoom(workspaceId)?.getContent() ?? EMPTY_DOC;
      const named: MockSnapshot = {
        id: `mock-${nextId++}`,
        kind: "named",
        title: title.trim(),
        summary: null,
        summary_status: "none",
        bytes: JSON.stringify(current).length,
        created_at: now(),
        content: current,
      };
      snapshotsFor(workspaceId).unshift(named);
      return strip(named);
    },

    async restoreSnapshot(workspaceId, snapshotId) {
      await sleep(delayMs);
      const list = snapshotsFor(workspaceId);
      const target = list.find((s) => s.id === snapshotId);
      if (!target) throw new ApiError("not_found", "That version no longer exists.");

      const room = getMockRoom(workspaceId);
      const current = room?.getContent() ?? EMPTY_DOC;
      const pre: MockSnapshot = {
        id: `mock-${nextId++}`,
        kind: "pre_restore",
        title: `Before restoring “${target.title ?? "version"}”`,
        summary: null,
        summary_status: "none",
        bytes: JSON.stringify(current).length,
        created_at: now(),
        content: current,
      };
      list.unshift(pre);
      room?.applyContent(target.content);
      return { restoredSnapshotId: target.id, preRestoreSnapshotId: pre.id };
    },

    async summarizeSnapshot(workspaceId, snapshotId) {
      await sleep(delayMs);
      const target = snapshotsFor(workspaceId).find((s) => s.id === snapshotId);
      if (!target) throw new ApiError("not_found", "That version no longer exists.");
      if (summaries >= summaryLimit) {
        throw new ApiError("ai_limit_reached", "Daily summary limit reached.", { resetAt: resetAt() });
      }
      summaries += 1;
      const first = plainText(target.content).replace(/\s+/g, " ").trim().slice(0, 140);
      const index = snapshotsFor(workspaceId).indexOf(target);
      const updated: MockSnapshot = { ...target, summary: first, summary_status: "done" };
      snapshotsFor(workspaceId)[index] = updated;
      return { summary: first, summary_status: "done" };
    },

    async *generate(input, signal) {
      const parsed = aiGenerateSchema.safeParse(input);
      if (!parsed.success) throw new ApiError("validation", "Invalid request", { status: 400 });
      const { prompt, tool, agent } = parsed.data;

      await sleep(delayMs, signal);
      if (prompt.includes("[daily]")) {
        throw new ApiError("daily_limit", "Daily platform limit reached.", { resetAt: resetAt() });
      }
      if (generations >= generationLimit || prompt.includes("[limit]")) {
        throw new ApiError("ai_limit_reached", "Daily generation limit reached.", { resetAt: resetAt() });
      }
      generations += 1;

      await sleep(streamDelayMs, signal);
      if (prompt.includes("[fail]")) {
        yield { event: "error", data: errorBody("internal", "The AI provider failed. Please try again.") } satisfies SseEvent;
        return;
      }

      const chunks = chunkText(cannedMarkdown(tool, agent));
      for (const [i, chunk] of chunks.entries()) {
        await sleep(streamDelayMs, signal);
        if (prompt.includes("[midfail]") && i === Math.floor(chunks.length / 2)) {
          yield { event: "error", data: errorBody("internal", "The AI provider stopped responding.") } satisfies SseEvent;
          return;
        }
        yield { event: "text", data: { text: chunk } } satisfies SseEvent;
      }
      yield {
        event: "done",
        data: { route: agent, usage: { tokensIn: Math.ceil(prompt.length / 4), tokensOut: Math.ceil(chunks.join("").length / 4) } },
      } satisfies SseEvent;
    },

    async getAiUsage(signal) {
      await sleep(delayMs, signal);
      const usage: AiUsageResponse = {
        day: new Date(now() * 1000).toISOString().slice(0, 10),
        generations: { used: generations, limit: generationLimit },
        summaries: { used: summaries, limit: summaryLimit },
        resetAt: resetAt(),
      };
      return usage;
    },

    async listAiKeys(orgId) {
      await sleep(delayMs);
      const last4 = keys.get(orgId);
      return last4 ? ([{ provider: "gemini", last4 }] satisfies AiKeyInfo[]) : [];
    },

    async putAiKey(orgId, apiKey) {
      await sleep(delayMs);
      if (apiKey.trim().length < 20) throw new ApiError("ai_key_invalid", "That key looks too short.");
      keys.set(orgId, apiKey.trim().slice(-4));
    },

    async testAiKey(orgId, request) {
      await sleep(delayMs * 2);
      const candidate = request.apiKey?.trim();
      if (candidate !== undefined && candidate !== "") {
        return candidate.length >= 20 ? { ok: true } : { ok: false, message: "That key was rejected by the provider." };
      }
      return keys.has(orgId) ? { ok: true } : { ok: false, message: "No key is stored yet." };
    },

    async uploadToPublicWorkspace(_orgId, file) {
      await sleep(delayMs);
      if (file.size > MAX_UPLOAD_BYTES) {
        throw new ApiError("payload_too_large", "That file is too large to upload.");
      }
      return {
        id: `upload-${nextId++}`,
        workspaceId: "mock-public",
        filename: file.name,
        contentType: file.type || "application/octet-stream",
        size: file.size,
        visibility: "published" as const,
        createdAt: now(),
      };
    },
  };
}
